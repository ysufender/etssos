#define DRIVERS_UART0_INT_RAW   (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000004))
#define DRIVERS_UART0_INT_STA   (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000008))
#define DRIVERS_UART0_INT_ENA   (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x0000000C))
#define DRIVERS_UART0_INT_CLR   (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000010))
#define DRIVERS_UART0_CLKDIV    (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000014))
#define DRIVERS_UART0_AUTOBAUD  (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000018))
#define DRIVERS_UART0_STATUS    (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x0000001C))
#define DRIVERS_UART0_CONF0     (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000020))
#define DRIVERS_UART0_CONF1     (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000024))
#define DRIVERS_UART0_LOWPULSE  (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000028))
