#define DRIVERS_UART0_RXD_CNT   (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000030))
#define DRIVERS_UART0_DATE      (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000034))
#define DRIVERS_UART0_ID        (*(volatile uint32_t*)(DRIVERS_UART0_PERI + 0x00000038))

